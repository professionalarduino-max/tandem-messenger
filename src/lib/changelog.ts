export const LATEST = CHANGELOG[0]

const SEEN_KEY = 'tandem:changelog-seen'

/** Показывать ли точку рядом с пунктом «Что нового». */
export function hasUnseenRelease() {
  try {
    return localStorage.getItem(SEEN_KEY) !== LATEST.version
  } catch {
    return false
  }
}

export function markReleasesSeen() {
  try {
    localStorage.setItem(SEEN_KEY, LATEST.version)
  } catch {
    // приватный режим — ничего страшного, точка просто останется
  }
}
